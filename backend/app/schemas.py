# ============================================================
# INPUT SCHEMAS
# ============================================================

class DisruptionInput(BaseModel):
    """
    Input provided to the Market Intelligence Agent.
    """
    news_text: str = Field(..., description="Raw news, weather, logistics, or disruption information")
    region: Optional[str] = Field(None, description="Affected geographical region if known")
    event_timestamp: Optional[datetime] = Field(None, description="Time at which the disruption was reported")
    source: Optional[str] = Field(None, description="Source of the disruption information")


# ============================================================
# AGENT 1: MARKET INTELLIGENCE
# ============================================================

class ThreatPayload(BaseModel):
    """
    Structured disruption information generated by the
    Market Intelligence Agent.
    """
    event_type: DisruptionTypeEnum
    region: str
    severity: SeverityEnum
    estimated_delay_days: int = Field(0, ge=0, description="Estimated supply or transportation delay")
    affected_materials: List[str] = Field(default_factory=list, description="Raw materials affected by the disruption")
    affected_products: List[ProductTypeEnum] = Field(default_factory=list, description="Bakery products potentially affected")
    affected_supplier_ids: List[int] = Field(default_factory=list)
    affected_route_ids: List[int] = Field(default_factory=list)
    capacity_reduction_percent: float = Field(0.0, ge=0, le=100)
    price_increase_percent: float = Field(0.0, ge=0)
    demand_change_percent: float = Field(0.0, description="Positive for demand increase, negative for decrease")
    duration_days: Optional[int] = Field(None, ge=0)
    summary: str = Field(..., description="Short structured summary of the disruption")
    confidence_score: float = Field(100.0, ge=0.0, le=100.0)


